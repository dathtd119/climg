"""Template output: 2-node .clab.yml and containerlab-app node-templates JSON."""

import json
import os

import yaml

from .util import ClimgError


def node_env(kind):
    env = {}
    if kind.qemu_env:
        env["QEMU_MEMORY"] = str(kind.resources["ram_mb"])
        env["QEMU_SMP"] = str(kind.resources["vcpu"])
    env.update({k: str(v) for k, v in kind.env.items()})
    return env


def iface_lines(kind):
    p = kind.ports
    first = p["first"]
    names = [p["data"].format(n=first + i) for i in range(3)]
    return (f"eth0 = mgmt ({p['mgmt']}); eth1 -> {names[0]}; eth2 -> {names[1]}; "
            f"eth{3} -> {names[2]}; ethN follows in order.")


def lab_name(kind, ver):
    safe = "".join(c if c.isalnum() else "-" for c in f"tpl-{kind.alias}-{ver}").lower()
    return safe.strip("-")


def render_topology(kind, tag, creds, ver, hint_ref):
    """(text, doc): header comments + YAML that `containerlab validate` accepts."""
    short = kind.alias.replace("_", "")
    kdef = {"image": tag, "credentials": {"username": creds["username"], "password": creds["password"]}}
    env = node_env(kind)
    if env:
        kdef["env"] = env
    doc = {"name": lab_name(kind, ver),
           "topology": {"kinds": {kind.name: kdef},
                        "nodes": {f"{short}1": {"kind": kind.name}, f"{short}2": {"kind": kind.name}},
                        "links": [{"endpoints": [f"{short}1:eth1", f"{short}2:eth1"]}]}}
    res = kind.resources
    ram = f"{res['ram_mb']} MB RAM, {res['vcpu']} vCPU" if kind.qemu_env else "VM size fixed by the vrnetlab launcher"
    head = [
        f"# Template: {kind.human_name} - 2 nodes back to back on the first data port (generated by climg).",
        f"# Image: {tag}",
        f"#   Missing image? climg pull {hint_ref} --yes",
        f"# Login: ssh {creds['username']}@<mgmt-ip> (credentials from the climg host config).",
        f"# Interfaces: {iface_lines(kind)}",
        f"# Resources per node: {ram}. Boot time budget: up to {kind.boot_budget_s // 60} min.",
    ]
    if not kind.confirmed:
        head.append("# Note: kind not smoke-tested by climg yet; run `climg test` before relying on it.")
    return "\n".join(head) + "\n" + yaml.safe_dump(doc, sort_keys=False), doc


def ui_entry(kind, tag, ver):
    return {"name": f"{kind.human_name} {ver}", "kind": kind.name, "image": tag,
            "icon": kind.ui.get("icon", "pe"), "baseName": kind.alias.replace("_", ""),
            "interfacePattern": kind.ports["data"].replace("{n}", "{n}"), "setDefault": False}


def merge_ui(path, entries):
    """Merge entries (by name) into the node-templates JSON array at path; returns (added, updated)."""
    cur = []
    if os.path.exists(path):
        with open(path) as f:
            cur = json.load(f)
        if not isinstance(cur, list):
            raise ClimgError(f"{path}: expected a JSON array of node templates")
    added = updated = 0
    for e in entries:
        for i, c in enumerate(cur):
            if c.get("name") == e["name"]:
                cur[i] = {**c, **{k: v for k, v in e.items() if k != "setDefault"}}
                updated += 1
                break
        else:
            cur.append(e)
            added += 1
    with open(path, "w") as f:
        json.dump(cur, f, indent=2)
        f.write("\n")
    return added, updated
